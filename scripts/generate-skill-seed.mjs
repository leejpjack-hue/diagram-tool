import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';

// One-time Workspace bootstrap + verified secondary bundle (agents:skills).
const root = resolve(import.meta.dirname, '..');
const skillName = 'type-to-flow';
const relativeFiles = [
  'SKILL.md',
  'references/flow-schema.md',
  'scripts/type-to-flow.js',
];

function computePackageChecksum(files) {
  const canonical = Object.entries(files)
    .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
    .map(([relPath, content]) => `${relPath}\0${content}\0`)
    .join('');
  return `sha256:${createHash('sha256').update(canonical, 'utf8').digest('hex')}`;
}

function extractVersion(skillMarkdown) {
  const match = skillMarkdown.match(/^\s*version:\s*["']?([^"'\r\n]+)["']?\s*$/m);
  const version = match?.[1]?.trim();
  if (!version) {
    throw new Error(`Skill ${skillName}/SKILL.md is missing metadata.version`);
  }
  return version;
}

const filePairs = await Promise.all(
  relativeFiles.map(async relPath => [
    relPath,
    await readFile(resolve(root, 'skills', skillName, relPath), 'utf8'),
  ]),
);
const packageFiles = Object.fromEntries(filePairs);
const starterEntries = filePairs.map(([relPath, content]) => [`${skillName}/${relPath}`, content]);
const version = extractVersion(packageFiles['SKILL.md']);
const checksum = computePackageChecksum(packageFiles);

const bundleManifest = {
  id: 'bundle:agents:skills',
  prefix: 'agents:skills',
  packages: [
    {
      name: skillName,
      version,
      checksum,
      location: `agents:skills/${skillName}`,
      files: relativeFiles,
    },
  ],
};

const secondaryBundle = {
  id: bundleManifest.id,
  prefix: bundleManifest.prefix,
  packages: [
    {
      name: skillName,
      version,
      checksum,
      location: `agents:skills/${skillName}`,
      files: packageFiles,
    },
  ],
};

await writeFile(resolve(root, 'skills/skills-bundle.json'), `${JSON.stringify(bundleManifest, null, 2)}\n`);
await writeFile(
  resolve(root, 'worker/generated-skill-seed.ts'),
  `// Generated by scripts/generate-skill-seed.mjs. Do not edit.\nexport const STARTER_SKILLS: Record<string, string> = ${JSON.stringify(Object.fromEntries(starterEntries), null, 2)};\n\nexport const SECONDARY_SKILL_BUNDLE = ${JSON.stringify(secondaryBundle, null, 2)} as const;\n`,
);


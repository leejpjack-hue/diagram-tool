import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';

// One-time bootstrap only. The durable Workspace becomes the source of truth.
const root = resolve(import.meta.dirname, '..');
const paths = [
  'type-to-flow/SKILL.md',
  'type-to-flow/references/flow-schema.md',
  'type-to-flow/scripts/type-to-flow.js',
];
const entries = await Promise.all(paths.map(async path => [path, await readFile(resolve(root, 'skills', path), 'utf8')]));
await writeFile(resolve(root, 'worker/generated-skill-seed.ts'), `// Generated by scripts/generate-skill-seed.mjs. Do not edit.\nexport const STARTER_SKILLS: Record<string, string> = ${JSON.stringify(Object.fromEntries(entries), null, 2)};\n`);
